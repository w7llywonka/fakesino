export function normalize(params = {}) {
  const rows = int(Number(params.rows ?? 16), 'rows', 8, 16);
  const risk = oneOf(params.risk ?? 'medium', 'risk', RISKS);
  return { rows, risk };
}

export function outcome(rng, params) {
  const path = rng.take(params.rows).map((f) => (f < 0.5 ? 0 : 1)); // 0 = left, 1 = right
  const bucket = path.reduce((a, b) => a + b, 0);
  const multiplier = TABLES[params.risk][params.rows][bucket];
  return { path, bucket, multiplier };
}

// Best case for the bet limits.
export const maxMultiplier = (params) => Math.max(...TABLES[params.risk][params.rows]);
